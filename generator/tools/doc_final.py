def append(name, text):
    global n
    p = os.path.join(DOCS, name)
    t = io.open(p, encoding=u"utf-8").read()
    io.open(p, u"w", encoding=u"utf-8").write(t.rstrip() + u"\n" + text)
    n += 1


def prepend(name, text):
    global n
    p = os.path.join(DOCS, name)
    t = io.open(p, encoding=u"utf-8").read()
    io.open(p, u"w", encoding=u"utf-8").write(text + t)
    n += 1


